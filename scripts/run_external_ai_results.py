"""
External AI Results Evaluator.
Imports a JSON list of test cases generated by another AI (ChatGPT / Claude / Gemini),
executes them all through SafeCodeAgent, and prints an evaluation report.
"""

import sys
import os
import json
import logging
from typing import List, Dict, Any

# Ensure project root is in sys.path
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from src.agents.safecode_agent import SafeCodeAgent

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger("ExternalAIEvaluator")

def evaluate_external_tests(json_file_path: str):
    with open(json_file_path, "r", encoding="utf-8") as f:
        test_cases: List[Dict[str, Any]] = json.load(f)

    agent = SafeCodeAgent()
    print(f"\n=================================================================")
    print(f" EVALUATING {len(test_cases)} EXTERNAL AI TEST CASES VIA SAFECODE-AI")
    print(f"=================================================================\n")

    passed = 0
    failed = 0

    for idx, tc in enumerate(test_cases, 1):
        t_id = tc.get("test_id", f"TC-{idx}")
        desc = tc.get("vulnerability_description", "Unspecified flaw")
        code = tc.get("code_snippet", "")
        cat = tc.get("category", "UNKNOWN")

        print(f"[{idx}/{len(test_cases)}] Running {t_id} | Category: {cat}")
        print(f"    Description: {desc}")

        try:
            res = agent.audit_and_patch(code, desc)
            if res.get("status") == "SUCCESS":
                passed += 1
                cls_info = res.get("taxonomy_classification", {})
                is_novel = res.get("zero_day_discovery", {}).get("is_novel_discovered", False)
                print(f"    -> RESULT: PASSED | Classified as [{cls_info.get('category_name')}] | Zero-Day: {is_novel}")
            else:
                failed += 1
                print(f"    -> RESULT: FAILED")
        except Exception as e:
            failed += 1
            print(f"    -> RESULT: ERROR ({e})")
        print("-" * 65)

    print(f"\n=================================================================")
    print(f" EVALUATION SUMMARY: {passed} PASSED | {failed} FAILED | TOTAL: {len(test_cases)}")
    print(f"=================================================================\n")

if __name__ == "__main__":
    if len(sys.argv) > 1:
        evaluate_external_tests(sys.argv[1])
    else:
        print("Usage: python scripts/run_external_ai_results.py <path_to_external_tests.json>")
